import type { AppFramework } from '../framework';
import { VercelCredentialError, vercelCredentialRejected } from './providers';

export class ProviderError extends Error {}

async function api<T = Record<string, any>>(provider: string, url: string, token: string, init: { method?: string; body?: unknown; headers?: Record<string, string> } = {}): Promise<{ status: number; body: T }> {
  const response = await fetch(url, {
    method: init.method ?? 'GET',
    headers: { authorization: `Bearer ${token}`, accept: 'application/json', 'content-type': 'application/json', ...init.headers },
    body: init.body === undefined ? undefined : JSON.stringify(init.body),
    signal: AbortSignal.timeout(60_000),
  });
  const body = await response.json().catch(() => ({})) as T;
  if (provider === 'Vercel' && vercelCredentialRejected(response.status, (body as any)?.error?.code, (body as any)?.error?.message ?? (body as any)?.message)) throw new VercelCredentialError();
  if (!response.ok && response.status !== 404 && response.status !== 409 && response.status !== 422) {
    const message = (body as any)?.message ?? (body as any)?.error?.message ?? response.statusText;
    throw new ProviderError(`${provider} request failed (${response.status}): ${String(message).slice(0, 300)}`);
  }
  return { status: response.status, body };
}

const GITHUB_HEADERS = { accept: 'application/vnd.github+json', 'x-github-api-version': '2022-11-28', 'user-agent': 'Mosaic-Cloud' };

const github = (token: string, path: string, method = 'GET', body?: unknown) => api('GitHub', `https://api.github.com${path}`, token, { method, body, headers: GITHUB_HEADERS });

/** Callers persist the returned name immediately so a retry never tries to create it again. */
export async function createGitHubRepository(input: { token: string; owner: string; name: string }): Promise<string> {
  const created = await github(input.token, '/user/repos', 'POST', { name: input.name, private: true, auto_init: true, description: 'Generated by Mosaic Cloud' });
  // Never commit into a repository Mosaic did not create: it could hold the user's unrelated work.
  if (created.status === 422) throw new ProviderError(`A GitHub repository named ${input.owner}/${input.name} already exists. Rename or remove it, then retry.`);
  if (created.status >= 400 || !created.body.full_name) throw new ProviderError(`GitHub could not create the repository (${created.status}).`);
  return String(created.body.full_name);
}

/** Commits the release as one commit that replaces the whole tree. */
export async function pushToGitHub(input: { token: string; repository: string; files: GeneratedFile[]; message: string }) {
  const gh = (path: string, method = 'GET', body?: unknown) => github(input.token, path, method, body);
  const fullName = input.repository;
  const repo = await gh(`/repos/${fullName}`);
  if (repo.status === 404) throw new ProviderError(`GitHub repository ${fullName} is no longer accessible.`);
  const branch = String(repo.body.default_branch ?? 'main');
  let ref;
  for (let attempt = 0; attempt < 5; attempt++) {
    ref = await gh(`/repos/${fullName}/git/ref/heads/${branch}`);
    if (ref.status !== 404 && ref.status !== 409) break;
    await new Promise((resolve) => setTimeout(resolve, 1000)); // auto_init commits asynchronously
  }
  if (!ref || ref.status >= 400) throw new ProviderError(`GitHub branch ${branch} is not ready in ${fullName}.`);
  const parent = String(ref.body.object.sha);
  const tree = await gh(`/repos/${fullName}/git/trees`, 'POST', { tree: input.files.map((file) => ({ path: file.path, mode: file.mode ?? '100644', type: 'blob', content: file.content })) });
  if (tree.status >= 400 || !tree.body.sha) throw new ProviderError(`GitHub rejected the release files (${tree.status}).`);
  const commit = await gh(`/repos/${fullName}/git/commits`, 'POST', { message: input.message, tree: tree.body.sha, parents: [parent] });
  if (commit.status >= 400 || !commit.body.sha) throw new ProviderError(`GitHub could not create the release commit (${commit.status}).`);
  const updated = await gh(`/repos/${fullName}/git/refs/heads/${branch}`, 'PATCH', { sha: commit.body.sha });
  if (updated.status >= 400) throw new ProviderError(`GitHub could not update the release branch (${updated.status}).`);
  return { repository: fullName, commit: String(commit.body.sha), url: `https://github.com/${fullName}` };
}

/** Creates a Neon project once; returns the connection string to store encrypted. */
export async function provisionNeon(input: { token: string; name: string }) {
  const created = await api('Neon', 'https://console.neon.tech/api/v2/projects', input.token, { method: 'POST', body: { project: { name: input.name } } });
  if (created.status >= 400) throw new ProviderError(`Neon could not create a project (${created.status}).`);
  const connectionUri = created.body.connection_uris?.[0]?.connection_uri;
  if (!connectionUri) throw new ProviderError('Neon did not return a connection string.');
  return { projectId: String(created.body.project.id), connectionUri: String(connectionUri) };
}

// shortcut: replays the idempotent initial migration each release; switch to versioned migrations once generated schemas evolve.
export async function applyMigration(connectionUri: string, sql: string) {
  const db = await createDb(connectionUri);
  // Drivers run queries as prepared statements, which allow one command each.
  const statements = sql.split(/;\s*(?:\n|$)/).map((statement) => statement.replace(/^\s*--.*$/gm, '').trim()).filter(Boolean);
  try { for (const statement of statements) await db.query(statement); } finally { await db.close(); }
}

const VERCEL = 'https://api.vercel.com';
// Team installs (Vercel OAuth integration) must name the team on every call; personal tokens omit it.
const vercelUrl = (path: string, teamId?: string | null) => { const url = new URL(path, VERCEL); if (teamId) url.searchParams.set('teamId', teamId); return url.toString(); };

export async function createVercelProject(input: { token: string; name: string; teamId?: string | null; framework?: AppFramework }): Promise<string> {
  const created = await api('Vercel', vercelUrl('/v11/projects', input.teamId), input.token, { method: 'POST', body: { name: input.name, framework: input.framework ?? 'sveltekit' } });
  if (created.status === 409) throw new ProviderError(`A Vercel project named ${input.name} already exists. Rename or remove it, then retry.`);
  if (created.status >= 400 || !created.body.id) throw new ProviderError(`Vercel could not create the project (${created.status}).`);
  return String(created.body.id);
}

export async function deployToVercel(input: { token: string; projectId: string; name: string; files: GeneratedFile[]; env: Record<string, string>; teamId?: string | null }) {
  const projectId = input.projectId;
  const workspace = input.files.some((file) => file.path === 'apps/web/package.json');
  const framework = releaseFramework(input.files);
  // Vercel can stage apps/web by itself when installing an uploaded release.
  const legacyAdapter = input.files.find((file) => file.path === 'scripts/vercel-adapter.ts');
  const config = input.files.find((file) => file.path === 'apps/web/vite.config.ts');
  const localAdapter = 'apps/web/scripts/vercel-adapter.ts';
  const files = config?.content.includes('../../scripts/vercel-adapter.ts') && legacyAdapter
    ? input.files.map((file) => file === config ? { ...file, content: file.content.replace('../../scripts/vercel-adapter.ts', './scripts/vercel-adapter.ts') } : file)
      .concat(input.files.some((file) => file.path === localAdapter) ? [] : [{ ...legacyAdapter, path: localAdapter }])
    : input.files;
  const settings = {
    framework,
    rootDirectory: workspace ? 'apps/web' : null,
    sourceFilesOutsideRootDirectory: workspace,
    installCommand: framework === 'nextjs' ? 'npm ci' : 'npm install',
    buildCommand: workspace || framework === 'nextjs' ? 'npm run build' : 'npm exec -- svelte-kit sync && npm run build',
  };
  // Older saved releases put the SvelteKit app at the repo root. Clear any stale project root before uploading them.
  const updated = await api('Vercel', vercelUrl(`/v9/projects/${projectId}`, input.teamId), input.token, { method: 'PATCH', body: settings });
  if (updated.status >= 400) throw new ProviderError(`Vercel could not update the project build settings (${updated.status}).`);
  for (const [key, value] of Object.entries(input.env)) {
    const configured = await api('Vercel', vercelUrl(`/v10/projects/${projectId}/env?upsert=true`, input.teamId), input.token, { method: 'POST', body: { key, value, type: 'encrypted', target: ['production', 'preview'] } });
    if (configured.status >= 400) throw new ProviderError(`Vercel could not set ${key} (${configured.status}).`);
  }
  const deployment = await api('Vercel', vercelUrl('/v13/deployments', input.teamId), input.token, {
    method: 'POST',
    body: { name: input.name, project: projectId, target: 'production', files: files.map((file) => ({ file: file.path, data: file.content })) },
  });
  if (deployment.status >= 400 || !deployment.body.id) throw new ProviderError(`Vercel rejected the deployment (${deployment.status}).`);
  return { projectId, deploymentId: String(deployment.body.id) };
}

export function releaseFramework(files: GeneratedFile[]): AppFramework {
  return files.some((file) => file.path === 'next.config.mjs') ? 'nextjs' : 'sveltekit';
}

export async function vercelDeploymentStatus(token: string, deploymentId: string, teamId?: string | null) {
  const result = await api('Vercel', vercelUrl(`/v13/deployments/${deploymentId}`, teamId), token);
  if (result.status === 404) throw new ProviderError('The Vercel deployment no longer exists.');
  const state = String(result.body.readyState ?? result.body.status ?? 'QUEUED');
  const host = (result.body.alias as string[] | undefined)?.[0] ?? result.body.url;
  return { state, url: host ? `https://${host}` : null, error: result.body.errorMessage ? String(result.body.errorMessage) : null };
}
